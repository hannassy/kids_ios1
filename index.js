// ---------------------------------------------------------------------------
// react-native-gesture-handler
// ---------------------------------------------------------------------------
// Библиотека обрабатывает жесты: свайп, долгое нажатие и т.д.
// React Navigation (боковое меню-drawer) использует её внутри.
//
// Документация требует: этот import должен быть САМЫМ ПЕРВЫМ в точке входа,
// до любых других import из react-native. Иначе на Android меню может глючить.
import "react-native-gesture-handler";

// ---------------------------------------------------------------------------
// expo (registerRootComponent)
// ---------------------------------------------------------------------------
// Expo — «обёртка» вокруг React Native: упрощает запуск на телефоне без Xcode/Android Studio.
// registerRootComponent — функция Expo, которая:
//   1) регистрирует наш корневой компонент App в системе;
//   2) подключает отрисовку и для нативного приложения, и для веба (через react-native-web).
import { registerRootComponent } from "expo";

// ---------------------------------------------------------------------------
// App.js — корень дерева компонентов
// ---------------------------------------------------------------------------
// App — главный компонент: в нём настроена навигация (меню и экраны).
// Путь "./App" без расширения — Node/Metro сам найдёт App.js.
import App from "./App";

// Запускаем приложение: с этого момента на экране рисуется то, что вернёт App().
registerRootComponent(App);
